  static const _ranks = [
    ('Ace', '王牌'),
    ('Two', '二'),
    ('Three', '三'),
    ('Four', '四'),
    ('Five', '五'),
    ('Six', '六'),
    ('Seven', '七'),
    ('Eight', '八'),
    ('Nine', '九'),
    ('Ten', '十'),
    ('Page', '侍从'),
    ('Knight', '骑士'),
    ('Queen', '王后'),
    ('King', '国王'),
  ];

  static List<TarotCard> _minor(
    String suit,
    String name,
    List<(String, String, String)> readings,
  ) => [
    for (var i = 0; i < _ranks.length; i++)
      TarotCard(
        '${_ranks[i].$1} of $suit',
        '$name${_ranks[i].$2}',
        readings[i].$1,
        readings[i].$2,
        readings[i].$3,
      ),
  ];

  static TarotCard? byId(String id) =>
      cards.where((card) => card.id == id).firstOrNull;
}
